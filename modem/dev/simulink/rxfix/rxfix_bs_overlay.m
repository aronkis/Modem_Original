function rxfix_bs_overlay(sys, base)
% rxfix_bs_overlay -- BS byte-seam census, as a MODEL overlay (cleanup
% sub-project 3, task 7).  Formerly the netlist injector
% modem/fixes/rxfix_inject.py's RXFIX_BS variant (module `bs_seam_census`).
% Env-gated: QPSK_RXFIX.  Registers 0x23C-0x258, freeze = fixctl bit 4 (the
% LEVEL W1 already uses).  The register layout of record is
% modem/fixes/fixes.toml [fixes.BS]; the injector's module is the bit truth:
%
%   0x23C bs_words   ByteSerializer words emitted           (WRAPS)
%   0x240 bs_starts  RxAlign start pulses = frame boundaries(WRAPS)
%   0x244 bs_push    ByteRxFifo pushes                      (WRAPS)
%   0x248 bs_pop     ByteRxFifo pops                        (WRAPS)
%   0x24C bs_drop    ByteRxFifo drop-oldest events          (WRAPS)
%   0x250 bs_marks   {bs_lasts[31:16], bs_markpush[15:0]}   (WRAPS, 52.6 s)
%   0x254 bs_evt     {trunc_last, trunc_min, trunc_max, dropmax}  (SATURATE)
%   0x258 bs_cnt     {bs_trunc[31:16], bs_q24[15:8], 8'b0}
%
% READ-ONLY INSTRUMENT: every signal is a tap and no existing line is re-driven,
% so the delivered byte-plane stream is unchanged by construction.
%
% ============================ FIVE THINGS THAT ARE NOT OBVIOUS ================
%
% (1) IT IS TWO BLOCKS, BECAUSE A SIMULINK BLOCK HAS ONE RATE.  The injector's
%     `bs_seam_census` is one always block with TWO clock enables: the
%     serializer counters are gated on `enbSer` (ByteSerializer's
%     enb_1_2_0_gated, 15.36 MHz) and the FIFO counters on `enbFifo`
%     (ByteRxFifo's enb_gated, 30.72 MHz).  A model block runs at ONE rate, and
%     a base-rate block reading the half-rate serializer would see every wv for
%     TWO base beats and count every word twice.  So:
%       BsSerCensus   at the serializer rate  -- words, starts, lasts, trunc,
%                     the three order statistics and q24;
%       BsSeamCensus  at the base rate        -- push, pop, drop, markpush,
%                     dropmax, PLUS the packing and the freeze shadow of all
%                     eight words, so one frozen sweep is still coherent to a
%                     single clk edge (the whole point of the instrument).
%     The five serializer-side quantities cross slow->fast through explicit
%     RateTransition blocks, the idiom byte_plumbing_overlay_k5.m already uses
%     for SerWordRT/SerTogRT/SerLastRT/SerFirstRT.  They cross as VALUES, not as
%     events, so the crossing cannot alias a count.
%
% (2) THE FIFO'S push/pop/drop ARE NOT VISIBLE TO A MODEL OVERLAY, AND ARE
%     DERIVED FROM ITS PORTS.  The shipped ByteRxFifo is the hand-authored
%     4096-deep BRAM drop-in modem/common/rxfifo/ByteRxFifo.v, installed over HDL
%     Coder's 64-deep register FIFO by modem/common/rxfifo/rxfifo_inject.sh (stage [4a/5] of
%     modem/fixes/build_base_tree.sh).  The injector patches THAT FILE and taps
%     its internal wires; a model overlay only ever sees the module's PORTS,
%     because HDL Coder generates the instantiation and the drop-in replaces the
%     module.  Port list (verified):
%       clk reset enb word tog wLast wFirst ready outWord valid outLast outFirst ovf
%     `ovf` is NOT a drop pulse -- in v5 it is the handshake DEBUG word on 0x1B0,
%     whose only drop information is the sticky bit 16 (`ovfCnt != 0`).  So the
%     three events are re-derived with the drop-in's OWN rules:
%       push = XOR edge of `tog`                    (drop-in: `tog != prev`)
%       pop  = valid & ready                        (drop-in: `valid_i && ready_1`;
%              `ready` is fed in RAW and HDL Coder's delay balancing pads it by the
%              same 4 beats it pads the FIFO's own `ready` with -- note (3))
%       drop = push && ((occ - pop) == 4095)        (drop-in: `push && (wr_p1 ==
%              rd_after_pop)`, which for DEPTH = 4096 is exactly that test on the
%              occupancy occ = wr - rd)
%     with occ carried as a shadow, occ <- occ + push - pop - drop (mod 4096).
%     Ledger: docs/evidence/sp3/BYTERXFIFO_DROPIN.md, which also says plainly
%     what `bs_drop == 0` does and does not prove on its own.
%
% (3) `ready` IS FED IN RAW, AND HDL CODER'S OWN DELAY BALANCING SUPPLIES THE
%     DROP-IN's `ready_1`.  This is MEASURED, not assumed, and the first regen of
%     this task is the measurement.  The drop-in pops on `ready` delayed FOUR
%     beats (`ready_1 = delayMatch_reg[3]`, shifted under `enb`) -- and that chain
%     is not a hand-written flourish: HDL Coder put it there.  The GENERATED
%     64-deep ByteRxFifo.v has the identical `delayMatch_reg[0] <= ready; ...
%     assign ready_1 = delayMatch_reg[3];`, because the FIFO block's other inputs
%     carry four cycles of inserted pipeline latency and `ready` (a composite
%     Inport) carries none, so the balancer pads it.  The census is in exactly the
%     same position, and takes exactly the same pad: with `byte_rx_ready` wired
%     straight in, `BsSeamCensus.v` reads `assign ready_1 = delayMatch_reg[3]` and
%     `pop = valid && ready_1` is the drop-in's rule beat for beat.
%
%     THE FIRST ATTEMPT HERE WAS A 4-DEEP `Delay` BLOCK OUTSIDE THE MLFB, on the
%     rxfix_steer_overlay.m "keep long paths out of the block" reasoning.  That
%     was WRONG and the regen said so: HDL Coder does not count a design `Delay`
%     as latency, so it padded the already-delayed input by four MORE and the
%     census computed `valid(k) && ready(k-8)` -- a four-beat differential error
%     in `bs_pop` that no static test could have caught.  The post-check that
%     pins this is a grep of the generated BsSeamCensus.v for a FOUR-deep
%     delayMatch on `ready`; `fixctl`, the other raw-Inport input, gets the same
%     pad and is the corroborating witness (a level, so its four beats are inert).
%
% (4) THE FREEZE IS TAKEN FROM THE COMPOSITE `fixctl` PORT, not from FixCtlDec.
%     FixCtlDec lives in Receiver/QPSK Rx and its w1Freeze output is already
%     consumed by rxfix_w1_overlay.m; bringing that bit back UP to the composite
%     would mean two more outports on QPSK Rx and Receiver and two more
%     keep_last dances, to deliver a bit that is already an input at this level.
%     `fixctl` is a composite Inport (beatfix_overlay.m), so the census decodes
%     bit 4 itself.  It is the same bit and the same level.
%
% (5) THE SERIALIZER TAPS ARE POST-PAD.  The injector's `assign bsWv = wv;` reads
%     the module-scope reg AFTER RXFIX_PAD has rewritten w/wv/wl in place, so on
%     a padded netlist bs_words counts FILLERS -- which is the only way the gate
%     row words191_k1536 (79,760 words for 418 frames) is reachable.  This
%     overlay's chart edit therefore inserts its taps immediately before the
%     `if wv` block that drives tog/heldWord, and leaves a marker comment that
%     rxfix_pad_overlay.m anchors its arbiter ABOVE.  Order in phase 2.21: BS
%     then PAD, exactly as the injector requires (PAD asserts the BS marker).
%
% G0: the whole body early-returns when QPSK_RXFIX is unset.  AXI mapping:
% patch_hdlworkflow_rxfix.m.  Gate: modem/gates/build_sro_bs.legs.

if isempty(getenv('QPSK_RXFIX')), return; end
if nargin < 1 || isempty(sys),  sys  = bdroot; end
if nargin < 2 || isempty(base), base = sys;    end
fprintf('=== rxfix_bs_overlay: byte-seam census (0x23C-0x258) ===\n');

lo  = 'LookUnderMasks';
ser = [base '/ByteSerializer'];
fif = [base '/ByteRxFifo'];

% ---- helpers (rxfix_w1_overlay.m idioms) ----------------------------------
  function n = leaf(pth)
    [~, n] = fileparts(pth);
  end
  function assert_block(pth)
    if isempty(find_system(fileparts(pth),'SearchDepth',1,lo,'all','Name',leaf(pth)))
      error('rxfix_bs: anchor missing: %s', pth);
    end
  end
  function h = oh(blk, k)
    p = get_param(blk,'PortHandles'); h = p.Outport(k);
  end
  function h = ih(blk, k)
    p = get_param(blk,'PortHandles'); h = p.Inport(k);
  end
  function p = next_outport(ss)
    p = numel(find_system(ss,'SearchDepth',1,lo,'all','BlockType','Outport')) + 1;
  end
  function idx = outport_by_name(ss, nm)
    b = find_system(ss,'SearchDepth',1,lo,'all','BlockType','Outport','Name',nm);
    if isempty(b), error('rxfix_bs: %s has no outport named %s', ss, nm); end
    idx = str2double(get_param(b{1},'Port'));
  end
  function keep_last(ss, names)
    % see rxfix_w1_overlay.m section (5): ddrcap_inject.py anchors on the two
    % beatfix ports being the LAST two outports of the composite.  Simulink
    % ROTATES rather than swaps, so each name is sent to the last index in turn.
    n = numel(find_system(ss,'SearchDepth',1,lo,'all','BlockType','Outport'));
    for j = 1:numel(names)
      b = find_system(ss,'SearchDepth',1,lo,'all','BlockType','Outport','Name',names{j});
      if isempty(b), error('rxfix_bs: %s has no outport named %s', ss, names{j}); end
      set_param(b{1}, 'Port', num2str(n));
    end
    for j = 1:numel(names)
      if outport_by_name(ss, names{j}) ~= n - numel(names) + j
        error('rxfix_bs: %s: %s did not land last (got %d of %d)', ss, names{j}, ...
              outport_by_name(ss, names{j}), n);
      end
    end
  end
  function h = src_of_inport(blk, k)
    % source port handle feeding input k of blk (used for the Receiver's
    % recStart, whose Receiver outport INDEX is not fixed by anything tracked --
    % byte_plumbing_overlay_k5.m resolves it from the port table at build time,
    % so the line is the only stable handle).
    L = get_param(ih(blk, k), 'Line');
    if L == -1, error('rxfix_bs: %s input %d is unconnected', blk, k); end
    h = get_param(L, 'SrcPortHandle');
  end
  function h = surface(ss, srch, nm)
    p = next_outport(ss);
    add_block('built-in/Outport', [ss '/' nm], 'Port', num2str(p));
    add_line(ss, srch, ih([ss '/' nm], 1), 'autorouting','on');
    h = oh(ss, p);
  end

% ---- idempotency (probe by block name) ------------------------------------
if ~isempty(find_system(base,'SearchDepth',1,lo,'all','Name','BsSeamCensus'))
  fprintf('rxfix_bs: already applied\n');
  return;
end

% ---- anchors ---------------------------------------------------------------
need = {ser, fif, [base '/SerTogRT'], [base '/SerFirstRT'], ...
        [base '/byte_rx_ready'], [base '/fixctl']};
for i = 1:numel(need), assert_block(need{i}); end
bfx = {'beatfix_viol_count','beatfix_viol_latch'};
for i = 1:numel(bfx)
  if isempty(find_system(base,'SearchDepth',1,lo,'all','BlockType','Outport','Name',bfx{i}))
    error(['rxfix_bs: composite outport %s missing -- QPSK_BEATFIX must be set ' ...
           'when beatfix_overlay.m runs (phase 2.20)'], bfx{i});
  end
end

% ---- (1) the three serializer taps, as chart outputs ------------------------
% String surgery on the chart script byte_plumbing_overlay_k5.m authored.  Each
% edit asserts its anchor; the whole block is skipped if the taps are already in.
S  = sfroot;
ch = S.find('Path', ser, '-isa', 'Stateflow.EMChart');
if isempty(ch), error('rxfix_bs: no Stateflow.EMChart at %s', ser); end
ch = ch(1);
sc = ch.Script;
if ~contains(sc, 'bsWv')
  a1 = 'function [word, wordTog, wordLast, wordFirst] = byteSerializerBlk(bitIn, bitValid, start, ready)';
  if ~contains(sc, a1)
    error('rxfix_bs: ByteSerializer signature anchor missing (script changed shape)');
  end
  sc = strrep(sc, a1, ...
    ['function [word, wordTog, wordLast, wordFirst, bsWv, bsWl, bsWcnt] = ' ...
     'byteSerializerBlk(bitIn, bitValid, start, ready)']);
  % bsWcnt is the PRE-step word count -- `start` clears state.wordCnt inside the
  % core, and the truncation predicate is about the words the start ABANDONS
  % (the injector's state_wordCnt_1, read at the top of the always block).
  a2 = '[w, wv, wl, ~, state] = qpskByteSerializer(';
  i2 = strfind(sc, a2);
  if numel(i2) ~= 1
    error('rxfix_bs: qpskByteSerializer call anchor occurs %d times', numel(i2));
  end
  sc = [sc(1:i2-1) ...
        'bsWcnt = state.wordCnt;   % BS census: words this step''s start would abandon' newline ...
        sc(i2:end)];
  % the taps sit immediately above the `if wv` that drives tog/heldWord, i.e.
  % AFTER any arbiter rxfix_pad_overlay.m inserts -- see header note (5).
  % NB the marker deliberately does NOT contain the literal `RXFIX_BS`: HDL Coder
  % copies MATLAB comments into the generated ByteSerializer.v, and
  % modem/rtl_sim/tree_marker.sh decides "injected tree" by grepping that file for
  % exactly that token -- measured, it reported a MODEL tree as `BS injector`.
  a3 = ['if wv' newline '    heldWord = w;'];
  if ~contains(sc, a3)
    error('rxfix_bs: ByteSerializer `if wv` anchor missing (script changed shape)');
  end
  sc = strrep(sc, a3, ...
    ['% BS byte-seam taps on the EMITTED word (rxfix_pad_overlay.m inserts its' newline ...
     '% filler/queue arbiter ABOVE this line, so these count fillers too).' newline ...
     'bsWv = wv; bsWl = logical(wl);' newline a3]);
  ch.Script = sc;
end
np = numel(get_param(ser,'PortHandles').Outport);
if np ~= 7
  error('rxfix_bs: ByteSerializer has %d outports after the script edit (want 7)', np);
end

% ---- (2) BsSerCensus: everything gated on the serializer enable --------------
% Cycle-accurate transcription of the enbSer half of rxfix_inject.py's
% bs_seam_census.  The counters are emitted LIVE (post-increment): the freeze
% shadow is BsSeamCensus's job, and the base-rate block is where the injector's
% one-shadow-per-clk coherence has to live.
% ---- geometry from the single source ---------------------------------------
% WPP (191 / 382) sizes the truncated-frame order statistics: 8-bit fields at
% f1536, 9-bit at f3072 (382 > 255). The packing of bs_evt follows: OW-bit
% tLast/tMin/tMax from the top, dropMax in the remaining 32-3*OW low bits
% (8 at f1536, 5 at f3072, saturating); q24 rides in sOrd's low field and is
% moved to bs_cnt[15:8]. The FIFO depth (4096 / 8192) is the BRAM drop-in's.
cfg = frame_config_k5();
WPP = cfg.WordsPerPacketRx; OW = 8 + double(WPP > 255); LOWB = 32 - 3*OW; LOWMAX = 2^LOWB - 1;
FD = cfg.RxFifoDepth; FDM = FD - 1;
lad = 24:24:WPP-1;
ladder = strjoin(arrayfun(@(k) sprintf('(dfc == uint16(%d))', k), lad, 'UniformOutput', false), ' || ');
add_block('simulink/User-Defined Functions/MATLAB Function', [base '/BsSerCensus'], ...
          'Position', [1060 1180 1200 1300]);
chS = S.find('Path', [base '/BsSerCensus'], '-isa', 'Stateflow.EMChart');
chS(1).Script = sprintf([ ...
'function [sWords, sStarts, sLasts, sTrunc, sOrd] = fcn(wv, wl, wcnt, sstart)\n' ...
'%%#codegen\n' ...
'%% RXFIX_BS, serializer half.  Every counter WRAPS (read as deltas); the three\n' ...
'%% order statistics and q24 SATURATE.  tMin resets to WPP and tMax to 0 so the\n' ...
'%% first event sets both.  MATLAB integer arithmetic SATURATES where the RTL\n' ...
'%% wraps, so each wrapping increment is written out explicitly.\n' ...
'persistent cWords cStarts cLasts cTrunc tLast tMin tMax q24\n' ...
'if isempty(cWords)\n' ...
'  cWords = uint32(0); cStarts = uint32(0); cLasts = uint16(0); cTrunc = uint16(0);\n' ...
'  tLast = uint16(0); tMin = uint16(%d); tMax = uint16(0); q24 = uint16(0);\n' ...
'end\n' ...
'if wv\n' ...
'  if cWords == uint32(4294967295), cWords = uint32(0); else, cWords = cWords + uint32(1); end\n' ...
'  if wl\n' ...
'    if cLasts == uint16(65535), cLasts = uint16(0); else, cLasts = cLasts + uint16(1); end\n' ...
'  end\n' ...
'end\n' ...
'if sstart\n' ...
'  if cStarts == uint32(4294967295), cStarts = uint32(0); else, cStarts = cStarts + uint32(1); end\n' ...
'  %% a start with 1..WPP-1 words accumulated is a TRUNCATED frame: those words never\n' ...
'  %% reach a wordLast.  wcnt == 0 is a clean boundary and wcnt == WPP cannot occur\n' ...
'  %% (the counter is cleared when it reaches WPP).\n' ...
'  if (wcnt >= uint16(1)) && (wcnt <= uint16(%d))\n' ...
'    wc8 = wcnt;\n' ...
'    if cTrunc == uint16(65535), cTrunc = uint16(0); else, cTrunc = cTrunc + uint16(1); end\n' ...
'    tLast = wc8;\n' ...
'    if wc8 < tMin, tMin = wc8; end\n' ...
'    if wc8 > tMax, tMax = wc8; end\n' ...
'    dfc = uint16(%d) - wc8;\n' ...
'    if %s\n' ...
'      if q24 ~= uint16(%d), q24 = q24 + uint16(1); end\n' ...
'    end\n' ...
'  end\n' ...
'end\n' ...
'sWords = cWords; sStarts = cStarts; sLasts = cLasts; sTrunc = cTrunc;\n' ...
'%% sOrd = {tLast, tMin, tMax, q24} (%d/%d/%d/%d bits) -- one 32-bit crossing instead of four.\n' ...
'sOrd = bitor(bitor(bitshift(uint32(tLast), %d), bitshift(uint32(tMin), %d)), ...\n' ...
'            bitor(bitshift(uint32(tMax), %d), uint32(q24)));\n'], ...
  WPP, WPP-1, WPP, ladder, LOWMAX, OW, OW, OW, LOWB, 32-OW, 32-2*OW, 32-3*OW);
sc4 = { oh(ser, 5), oh(ser, 6), oh(ser, 7), src_of_inport(ser, 3) };
for k = 1:4
  add_line(base, sc4{k}, ih([base '/BsSerCensus'], k), 'autorouting','on');
end

% ---- (3) the five slow->fast crossings --------------------------------------
rtn = {'BsRtWords','BsRtStarts','BsRtLasts','BsRtTrunc','BsRtOrd'};
rth = cell(1,5);
for k = 1:5
  add_block('built-in/RateTransition', [base '/' rtn{k}], ...
            'OutPortSampleTime','1/30.72e6', 'Position', [1240 1180+28*k 1280 1200+28*k]);
  add_line(base, oh([base '/BsSerCensus'], k), ih([base '/' rtn{k}], 1), 'autorouting','on');
  rth{k} = oh([base '/' rtn{k}], 1);
end

% ---- (4) BsSeamCensus: the FIFO half, the packing and the freeze shadow ------
add_block('simulink/User-Defined Functions/MATLAB Function', [base '/BsSeamCensus'], ...
          'Position', [1340 1160 1500 1420]);
chB = S.find('Path', [base '/BsSeamCensus'], '-isa', 'Stateflow.EMChart');
chB(1).Script = sprintf([ ...
'function [cWords, cStarts, cPush, cPop, cDrop, cMarks, cEvt, cCnt] = fcn(sWords, sStarts, sLasts, sTrunc, sOrd, tog, wFirst, valid, ready, fixctl)\n' ...
'%%#codegen\n' ...
'%% RXFIX_BS, FIFO half + packing + shadow.  STATEMENT ORDER IS THE RTL''S, not\n' ...
'%% the natural one (rh_w1_census / RxW1Census precedent): `assign bus = {s7..s0}`\n' ...
'%% means the value visible during beat k is the shadow CAPTURED at edge k-1, and\n' ...
'%% the shadow takes the PRE-increment counters.  So: outputs first, then the\n' ...
'%% capture, then the increments.  freeze is a LEVEL -- the shadows hold while the\n' ...
'%% live counters keep running.\n' ...
'persistent prevTog occ lPush lPop lDrop lMarkP dropRun dropMax s0 s1 s2 s3 s4 s5 s6 s7\n' ...
'if isempty(prevTog)\n' ...
'  prevTog = false; occ = uint16(0);\n' ...
'  lPush = uint32(0); lPop = uint32(0); lDrop = uint32(0); lMarkP = uint16(0);\n' ...
'  dropRun = uint16(0); dropMax = uint16(0);\n' ...
'  s0 = uint32(0); s1 = uint32(0); s2 = uint32(0); s3 = uint32(0);\n' ...
'  s4 = uint32(0); s5 = uint32(0); s6 = uint32(0); s7 = uint32(0);\n' ...
'end\n' ...
'cWords = s0; cStarts = s1; cPush = s2; cPop = s3;\n' ...
'cDrop = s4; cMarks = s5; cEvt = s6; cCnt = s7;\n' ...
'%% the three seam events, from the BRAM drop-in''s PORTS and its own rules\n' ...
'%% (docs/evidence/sp3/BYTERXFIFO_DROPIN.md): push = tog edge, pop = valid_i &&\n' ...
'%% ready_1, drop = the drop-OLDEST test wr+1 == rd_after_pop on the occupancy.\n' ...
'push = (logical(tog) ~= prevTog);\n' ...
'pop  = logical(valid) && logical(ready);   %% HDL Coder pads `ready` by 4 = the drop-in''s ready_1\n' ...
'pN = uint16(0); if pop, pN = uint16(1); end\n' ...
'%% + DEPTH before the subtract: MATLAB unsigned arithmetic SATURATES at 0 where\n' ...
'%% the RTL pointer wraps, and this test is exactly about the wrap.\n' ...
'drop = push && (bitand(occ + uint16(%d) - pN, uint16(%d)) == uint16(%d));\n' ...
'dN = uint16(0); if drop, dN = uint16(1); end\n' ...
'uN = uint16(0); if push, uN = uint16(1); end\n' ...
'%% the eight words as wires off THIS beat''s inputs and the PRE-edge counters\n' ...
'w0 = sWords;\n' ...
'w1 = sStarts;\n' ...
'w2 = lPush;\n' ...
'w3 = lPop;\n' ...
'w4 = lDrop;\n' ...
'w5 = bitor(bitshift(uint32(sLasts), 16), uint32(lMarkP));\n' ...
'%% w6 = {tLast, tMin, tMax, dropMax}: sOrd carries the first three, q24 is in its\n' ...
'%% low %d bits and belongs to w7.\n' ...
'w6 = bitor(bitand(sOrd, uint32(%d)), uint32(dropMax));\n' ...
'w7 = bitor(bitshift(uint32(sTrunc), 16), bitshift(bitand(sOrd, uint32(%d)), 8));\n' ...
'%% freeze = fixctl bit 4 (header note 4), the same level W1 shadows behind\n' ...
'if bitand(uint32(fixctl), uint32(16)) == uint32(0)\n' ...
'  s0 = w0; s1 = w1; s2 = w2; s3 = w3; s4 = w4; s5 = w5; s6 = w6; s7 = w7;\n' ...
'end\n' ...
'%% live counters, incremented AFTER the capture; the 32/16-bit ones WRAP\n' ...
'if push\n' ...
'  if lPush == uint32(4294967295), lPush = uint32(0); else, lPush = lPush + uint32(1); end\n' ...
'  if wFirst\n' ...
'    if lMarkP == uint16(65535), lMarkP = uint16(0); else, lMarkP = lMarkP + uint16(1); end\n' ...
'  end\n' ...
'  %% drop implies push in this RTL, so the run length advances on pushes only\n' ...
'  if drop\n' ...
'    if dropRun ~= uint16(%d), dropRun = dropRun + uint16(1); end\n' ...
'  else\n' ...
'    dropRun = uint16(0);\n' ...
'  end\n' ...
'  if dropRun > dropMax, dropMax = dropRun; end\n' ...
'end\n' ...
'if pop\n' ...
'  if lPop == uint32(4294967295), lPop = uint32(0); else, lPop = lPop + uint32(1); end\n' ...
'end\n' ...
'if drop\n' ...
'  if lDrop == uint32(4294967295), lDrop = uint32(0); else, lDrop = lDrop + uint32(1); end\n' ...
'end\n' ...
'occ = bitand(occ + uint16(%d) + uN - pN - dN, uint16(%d));\n' ...
'prevTog = logical(tog);\n'], ...
  FD, FDM, FDM, LOWB, 4294967295 - LOWMAX, LOWMAX, LOWMAX, FD, FDM);
cen = [base '/BsSeamCensus'];
ins = [rth, {oh([base '/SerTogRT'], 1), oh([base '/SerFirstRT'], 1), ...
