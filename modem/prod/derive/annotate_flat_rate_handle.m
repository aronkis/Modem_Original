function annotate_flat_rate_handle(sys)
% annotate_flat_rate_handle -- explanatory notes inside the Rate Handle subsystem
% of the FLAT reference model (make_flat_model.m).  Documentation only: adds
% Simulink annotations and a block Description, moves no blocks, adds no lines.
% Idempotent: existing notes tagged RH_NOTE are deleted and re-created.
%
% Sources for the text: the stock commhdlQPSKTxRx example, beatobs_overlay.m,
% beatfix_overlay.m (bfGridEn / BfGridPace), rxfix_w1_overlay.m (w1* taps),
% rxfix_steer_overlay.m + rxfix/README.md (RxSteer, fixctl bit 5).
if nargin < 1 || isempty(sys), sys = bdroot; end
rh = [sys '/TxRxComposite/Receiver/QPSK Rx/Frequency and Time Synchronizer/Symbol Synchronizer/Rate Handle'];
assert(~isempty(find_system(sys,'SearchDepth',6,'LookUnderMasks','all','Name','Rate Handle')), 'Rate Handle not found');

old = find_system(rh,'SearchDepth',1,'FindAll','on','Type','Annotation','Tag','RH_NOTE');
for h = reshape(old,1,[]), delete(h); end

purpose = sprintf([ ...
 'RATE HANDLE -- purpose\n' ...
 'The Symbol Synchronizer''s interpolator emits one symbol per timing-loop strobe, so its output is\n' ...
 'valid on an IRREGULAR beat (the strobe drifts with the sample-rate offset and the timing correction).\n' ...
 'Everything downstream (CFC, carrier sync, preamble detector, packet controller, demod) assumes a\n' ...
 'REGULAR symbol stream: one valid in exactly 4 rail beats (sps = 4).  This block converts the former\n' ...
 'to the latter with a small FIFO:\n' ...
 '   push  = strobe            (dataIn is written whenever the interpolator produced a symbol)\n' ...
 '   pop   = validIn & (phase == 0)   where phase is the free-running mod-4 HDL Counter\n' ...
 'so validOut/dataOut are a 1-in-4 symbol stream and the FIFO absorbs the jitter between the two rates.\n' ...
 'If the input runs slow the FIFO drains (EMPTY edge); if it runs fast it fills (FULL edge).  Those two\n' ...
 'edges are the receiver''s only rate-mismatch failure points, which is why every fix and instrument\n' ...
 'in this subsystem watches or steers the pop.\n' ...
 'Stock blocks: dataIn, strobe, validIn, Constant, FIFO, HDL Counter, Compare To Constant,\n' ...
 'Logical Operator, dataOut, validOut.  Everything else was added by the overlay stack (notes below).']);

pacer = sprintf([ ...
 'bfGridEn / BfGridPace  (beatfix_overlay.m, fixctl 0x208 bit 2)\n' ...
 'Selects which mod-4 phase counter drives the pop grid.  en = 0: the stock HDL Counter\n' ...
 '(counts validIn beats).  en = 1: an absolute pacer that counts EVERY rail beat, so the pop\n' ...
 'grid cannot slip when validIn drops out.  Default off = legacy-identical.']);

taps = sprintf([ ...
 'Witness taps (read-only, no effect on the data path)\n' ...
 'beatobsRhCtr / beatobsPush / beatobsPop  (beatobs_overlay.m): the mod-4 phase pointer and the FIFO\n' ...
 '   push/pop pointers, routed up to the debug capture bus.\n' ...
 'w1Strobe / w1Occ / w1PopEmpty / w1PushFull / w1PushPtr / w1PopPtr  (rxfix_w1_overlay.m): the W1 census\n' ...
 '   inputs.  w1Occ is the FIFO''s registered TRUE occupancy (not a pointer delta), counted by RxW1Census\n' ...
 '   in the Frequency and Time Synchronizer into AXI 0x214-0x230 (0x220 = this block''s validOut count).']);

steer = sprintf([ ...
 'RxSteer -- pop steering  (rxfix_steer_overlay.m; formerly netlist variants R4B / R4D)\n' ...
 'Keeps the FIFO away from its EMPTY and FULL edges by editing the pop, once per 13-slot window:\n' ...
 '   window opens on sroPcEnd (Packet Controller endOut), lock after 8 windows\n' ...
 '   occ <= 8   -> arm skipEn  : suppress one nominal pop        (EMPTY-edge guard, always on)\n' ...
 '   occ >= 24  -> arm extraEn : insert one extra pop at phase 2 (FULL-edge guard, only if sroSign = 1)\n' ...
 '   pop = (popNom & ~skipEn) | (extraEn & validIn & phase2 & sroSign)\n' ...
 'sroSign is fixctl bit 5: 0 = R4B behaviour (148, negative SRO), 1 = R4D (146, positive SRO).\n' ...
 'The pop expression is built from the AND/NOT/OR primitives OUTSIDE the MATLAB Function block, and\n' ...
 'sroPcEnd / occ enter through Delay blocks, so HDL Coder cannot add a delay-match register that\n' ...
 'would move the pop by a beat.  Witnesses: r4_wit 0x234 {locked, skips, opens}, r4_extras 0x238,\n' ...
 'sro_mode 0x25C {extraArmed, sroSign}.']);

notes = { ...
  purpose, [-600 -600], 10, [0.97 0.95 0.88]; ...
  pacer,   [-600 -400], 9,  [0.91 0.86 0.63]; ...
  taps,    [-170  520], 9,  [0.83 0.88 0.93]; ...
  steer,   [ 860   20], 9,  [0.97 0.78 0.64]};
for k = 1:size(notes,1)
  a = Simulink.Annotation(rh, notes{k,1});
  a.Position = notes{k,2};
  a.FontSize = notes{k,3};
  a.BackgroundColor = sprintf('[%.2f, %.2f, %.2f]', notes{k,4});
  a.HorizontalAlignment = 'left';
  a.Tag = 'RH_NOTE';
end

% Also on the block itself, so the tooltip / dialog carries the one-line version.
set_param(rh, 'Description', ['Rate Handle: turns the Symbol Synchronizer''s strobe-timed (irregular) ' ...
  'symbol output into a regular 1-in-4 symbol stream through a small FIFO (push on strobe, pop on the ' ...
  'mod-4 grid). Overlays added the bfGridEn pacer (fixctl bit 2), the beatobs/W1 witness taps, and ' ...
  'RxSteer pop steering (fixctl bit 5 = sroSign). See the notes inside the subsystem.']);
fprintf('RH_NOTES_OK: %d annotations in %s\n', size(notes,1), rh);
end
